public class Main {
    public static void main(String[] args) {
        // println() shows text and then moves to a new line.
        System.out.println("Hello, Vista Ridge!");

        // + joins text and values into one String.
        System.out.println("Score: " + 95 + " points");

        // print() stays on the same line.
        System.out.print("Loading");
        System.out.println("...done");

        // An empty println() makes a blank line.
        System.out.println();
        System.out.println("Ready.");
    }
}
