// console.log() shows text in the console and then moves to a new line.
console.log("Hello, Vista Ridge!");

// Separate several values with commas. console.log() puts a space between them.
console.log("Score:", 95, "points");

// process.stdout.write() does not end the line.
process.stdout.write("Loading");
console.log("...done");

// An empty console.log() makes a blank line.
console.log();
console.log("Ready.");
