# print() shows text in the console and then moves to a new line.
print("Hello, Vista Ridge!")

# Separate several values with commas. print() puts a space between them.
print("Score:", 95, "points")

# end="" keeps the next print on the same line.
print("Loading", end="")
print("...done")

# An empty print() makes a blank line.
print()
print("Ready.")
